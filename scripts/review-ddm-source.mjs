import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const sourceUrl='https://rapid.ddm.gov.bd/service/shelter_info';
export function reviewDdmSource(html, retrievedAt, manifest) {
  const declarations=[...html.matchAll(/(?:const|let|var)\s+shelter\s*=\s*/g)];
  if (declarations.length!==1) throw Error('ddm-inline-inventory-missing-or-ambiguous');
  const declaration=declarations[0];
  // Parse a JSON array only; never execute provider JavaScript.
  const start=declaration.index+declaration[0].length;
  let depth=0,quoted=false,escaped=false,end=-1;
  if (html[start]!=='[') throw Error('ddm-inventory-not-json-array');
  for(let i=start;i<html.length;i++) {
    const ch=html[i];
    if(quoted){if(escaped)escaped=false;else if(ch==='\\')escaped=true;else if(ch==='"')quoted=false;continue;}
    if(ch==='"')quoted=true;
    else if(ch==='[')depth++;
    else if(ch===']'&&--depth===0){end=i+1;break;}
  }
  if(end<0)throw Error('ddm-inventory-incomplete');
  const records=JSON.parse(html.slice(start,end));
  if(!records.length)throw Error('ddm-inventory-empty');
  const [west,south,east,north]=manifest.bbox;
  let coordinatePairCount=0,withinStudyExtentCount=0;
  const numeric=value=>(typeof value==='number'||typeof value==='string'&&value.trim()!=='')&&Number.isFinite(Number(value));
  for(const record of records) {
    if(!numeric(record.lat)||!numeric(record.lon))continue;
    const lat=Number(record.lat),lon=Number(record.lon);
    if(Math.abs(lat)>90||Math.abs(lon)>180||(lat===0&&lon===0))continue;
    coordinatePairCount++;
    if(lon>=west&&lon<=east&&lat>=south&&lat<=north)withinStudyExtentCount++;
  }
  if(!Number.isFinite(Date.parse(retrievedAt)))throw Error('ddm-review-missing-retrieval-date');
  return {
    sourceUrl,retrievedAt,observedAt:null,
    sourceSha256:createHash('sha256').update(html).digest('hex'),
    structure:'html-table-and-inline-json',
    method:'Parse the shelter JSON array embedded in the source page; count finite non-origin coordinate pairs and points inside the population-grid extent. Do not execute scripts or import records.',
    recordCount:records.length,coordinatePairCount,withinStudyExtentCount,
    studyExtentSource:'/data/people-manifest.json',studyExtentBbox:manifest.bbox,
    recordGeometryStatus:'unreviewed',reuseStatus:'unreviewed',
    excludedFields:['contact_person','contact_no'],
    limitations:[
      'Source structure and coordinate presence reviewed; individual location accuracy and source update date are unknown.',
      'Within-extent count is not DNCC/DSCC coverage, unique buildings or operational shelter availability.',
      'Source-reported capacity, status and accessibility fields are not independently verified readiness.',
      'No separate API or reuse licence established by this page inspection.',
      'No source records, coordinates or personal contacts are included in this aggregate review.',
    ],
  };
}

if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const input=process.argv[2],retrievedAt=process.argv[3];
  if(!input||!retrievedAt)throw Error('Usage: node scripts/review-ddm-source.mjs /private/path/source.html ACTUAL_CAPTURE_TIMESTAMP_ISO');
  const review=reviewDdmSource(readFileSync(input,'utf8'),retrievedAt,JSON.parse(readFileSync('public/data/people-manifest.json','utf8')));
  writeFileSync('public/data/ddm-source-review.json',JSON.stringify(review,null,2)+'\n');
  writeFileSync('src/ddm-source-review.ts','// Generated by scripts/review-ddm-source.mjs. Aggregate metadata only; no source records or contacts.\nexport const DDM_SOURCE_REVIEW = '+JSON.stringify(review,null,2)+' as const;\n');
  console.log(`Reviewed source structure: ${review.recordCount} records, ${review.coordinatePairCount} coordinate pairs, ${review.withinStudyExtentCount} inside study extent; no records imported.`);
}
